"""
    _centpoly_roots_in(c, da, db, atol) -> Vector{T}

Find interior breakpoints for the centered monomial polynomial

    p(Δx) = c[1] + c[2]·Δx + c[3]·Δx² + … + c[P+1]·Δx^P,

where `Δx = x - x0` is the coordinate relative to the span midpoint `x0`.
The arguments `da = a - x0 < 0` and `db = b - x0 > 0` are the span endpoints
`[a, b]` expressed in these same shifted coordinates. Breakpoints are returned
in shifted coordinates.

These breakpoints are used to partition the span when integrating `|p|`. The
important requirement is therefore that no root at which `p` changes sign is
missed. Additional breakpoints are harmless, since subdividing an interval on
which `p` has constant sign does not change

    ∫ |p(x)| dx = |∫ p(x) dx|.

Accordingly, the routine may conservatively return a point that is not an exact
root when the discriminant is numerically close to zero.

The effective degree is determined by stripping trailing coefficients smaller
than `atol * max(1, ‖c‖∞)`. Breakpoints within `atol` of an endpoint are
excluded.

**Algorithm**:
- Degree 0: no breakpoints.
- Degree 1: direct formula `r = -c[1]/c[2]`.
- Degree 2: standard quadratic formula. If the discriminant is numerically
  indistinguishable from zero, the quadratic vertex is retained as a
  conservative breakpoint.
- Degree 3: delegates to `_cubic_roots_in`, which uses the critical points of
  the cubic to partition the span into monotone intervals and locates every
  sign-changing root by bisection.

Errors if the effective degree exceeds 3.
"""
function _centpoly_roots_in(
    c    :: Vector{T},
    da   :: T,
    db   :: T,
    atol :: T,
) ::Vector{T} where {T<:AbstractFloat}

    p     = length(c) - 1
    scale = max(one(T), maximum(abs, c))

    while p > 0 && abs(c[p + 1]) < atol * scale
        p -= 1
    end

    _in(r) = da + atol < r < db - atol

    p == 0 && return T[]

    if p == 1
        r = -c[1] / c[2]
        return _in(r) ? T[r] : T[]
    end

    if p == 2
        A, B, C = c[3], c[2], c[1]
        disc = B^2 - T(4) * A * C

        scale_disc = B^2 + T(4) * abs(A * C) + eps(T)
        tol_disc   = T(1e3) * eps(T) * scale_disc

        disc < -tol_disc && return T[]

        inv2A = inv(T(2) * A)

        # If the discriminant is numerically close to zero, there may be either
        # no real root or one repeated real root. Since these points are used
        # only as integration breakpoints, conservatively retain the vertex.
        if disc <= tol_disc
            r = -B * inv2A
            return _in(r) ? T[r] : T[]
        end

        sq = sqrt(disc)
        return sort!(filter(_in, [
            (-B - sq) * inv2A,
            (-B + sq) * inv2A,
        ]))
    end

    p == 3 ||
        error("_centpoly_roots_in: degree $p > 3 not supported")

    return _cubic_roots_in(
        c[1],
        c[2],
        c[3],
        c[4],
        da,
        db,
        atol,
    )
end


"""
    _cubic_roots_in(C0, C1, C2, C3, da, db, atol) -> Vector{T}

Find interior breakpoints for the cubic

    p(t) = C3·t³ + C2·t² + C1·t + C0

on `(da, db)`.

This routine is used to partition the span when integrating `|p|`. The
important requirement is that no root at which `p` changes sign is missed;
additional breakpoints are harmless.

The critical points of the cubic are the roots of

    p'(t) = 3C3·t² + 2C2·t + C1.

They partition the interval into pieces on which `p` is monotone. The critical
points are found using `_centpoly_roots_in` and retained as conservative
breakpoints. On each monotone interval whose endpoint values have opposite
signs, the unique sign-changing root is located using a bracketed root solve.

Returned breakpoints are sorted and lie at least `atol` away from the span
endpoints.
"""
function _cubic_roots_in(
    C0   :: T,
    C1   :: T,
    C2   :: T,
    C3   :: T,
    da   :: T,
    db   :: T,
    atol :: T,
) ::Vector{T} where {T<:AbstractFloat}

    _in(r) = da + atol < r < db - atol
    f(t)   = ((C3 * t + C2) * t + C1) * t + C0

    # Critical points are the roots of
    # p'(t) = C1 + 2C2*t + 3C3*t².
    dc   = T[C1, T(2) * C2, T(3) * C3]
    crit = _centpoly_roots_in(dc, da, db, atol)

    # Critical points are conservative integration breakpoints.
    roots = copy(crit)
    pts   = vcat(da, crit, db)

    @inbounds for k in 1:length(pts)-1
        a  = pts[k]
        b  = pts[k+1]
        fa = f(a)
        fb = f(b)

        if (fa < zero(T) && fb > zero(T)) ||
           (fa > zero(T) && fb < zero(T))

            r = find_zero(f, (a, b), Bisection(); xatol=atol)
            _in(r) && push!(roots, r)
        end
    end

    return sort!(roots)
end
