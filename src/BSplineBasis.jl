"""
    struct PolyPiece{T,N}
A single polynomial piece of the B-spline on ([0,1]).

Type Parameters:
- `T` : numeric type (e.g., Float64, BigFloat)
- `N` : number of coefficients (= degree+1)

Fields:
- `a,b`    :: T,T        # endpoints in [0,1]
- `x0`     :: T          # center point of support for monomial expansion: (a+b)/2
- `coeffs` :: NTuple{N,T}  # coefficients (c₀, c₁, …, c_{N-1}) for centered monomial basis
                          # on [a,b]:  S(x) = ∑_{k=0}^{N-1} c_k * (x - x0)^k
"""
struct PolyPiece{T,N}
    a::T
    b::T
    x0::T
    coeffs::NTuple{N,T}
end

# constructor for empty coeffs (filled with zeros). fill later with with_coeffs
@inline _mk_piece(::Val{P}, a::T, b::T) where {T<:AbstractFloat,P} =
    PolyPiece{T,P+1}(a, b, (a+b)/T(2), ntuple(_->zero(T), P+1))


# struct is immutable, once coefficients are computed copy into new struct with coeffs
@inline with_coeffs(pp::PolyPiece{T,N}, c::NTuple{N,T}) where {T<:AbstractFloat,N} =
    PolyPiece{T,N}(pp.a, pp.b, pp.x0, c)

    
"""
    poly_intervals(bfun) -> Vector{Tuple{T,T}}

Returns the intervals on which the B-spline `bfun` is a single
polynomial piece for a periodic or non-periodic basis. 

**WARNING: Other Functions in this package are not designed to support periodic splines**

- Works for periodic and non-periodic bases (BSplineKit) of BSplines on [0,1]
- For periodic splines all pieces are mapped back to [0,1] via mod 1.
- Requires the knot vector to include 0 and 1; zero-length spans are omitted.

Arguments
- `bfun`: A B-spline basis function, see examples

Returns
- Vector of `(a,b)` tuples delimiting polynomial support intervals.

# Examples
B = BSplines.BSplineBasis(BSplineOrder(4), breakpoints)
bfun = B[1]
ivs = poly_intervals(bfun)
"""
function poly_intervals(bfun)

    rng = BSK.BSplines.support(bfun)  # range of knot vector indices where bfun is nonzero
    _basis = BSK.BSplines.basis(bfun)
    T     = eltype(BSK.knots(_basis))
    τ     = collect(T, BSK.knots(_basis)) # knot vector

    T(0) in τ && T(1) in τ || throw(ArgumentError("Knots must include 0 and 1"))

    spans = Tuple{T,T}[]
    for k in rng.start:rng.stop-1
        push!(spans, (τ[k], τ[k+1]))
    end

    filter!(x-> x[1] != x[2], spans) # Filter out zero-length spans

    all(a < b && !(a < 0 && b > 0) && !(a<1 && b>1) for (a, b) in spans) ||
        throw(ArgumentError("Spans must be non-degenerate and not cross 0/1"))
    map!(Utils.mod_interval, spans, spans) # map back to [0,1]
    sort!(spans; by = t -> t[1])

    return spans
end


"""
    polynomial_pieces(bfun) -> Vector{PolyPiece{T}}

Return all polynomial pieces of a single B-spline `bfun` without centered monomial
coefficients. Assumes that bfun is from a BSplineKit basis on [0,1] with knots including 0 and 1. See
`poly_intervals` for details on interval construction.
"""
function polynomial_pieces(bfun, ::Val{P}) where {P}
    basis = BSK.BSplines.basis(bfun)
    T     = eltype(BSK.knots(basis))

    pieces = PolyPiece{T,P+1}[]

    intervals = poly_intervals(bfun)  
    for (left, right) in intervals
        push!(pieces, _mk_piece(Val(P), T(left), T(right)))
    end

    return pieces
end


"""
    centered_monomial_coeffs(S::BSplineKit.Spline, x_c)

Computes the coefficients for a centered polynomial representation via Taylor expansion of S around
x_c. returns the tuple of coefficients `(c₀, c₁, …, c_p)` such that on the interval
containing `x_c`,

    S(x) = ∑ₖ cₖ * (x - x_c)^k,

where `S` is a BSplineKit spline of degree `p`.

Each coefficient is computed as cₖ = S^{(k)}(x_c) / k!.
"""
function centered_monomial_coeffs(S::BSK.Spline{T}, x_c::T) where {T<:AbstractFloat}
    p = BSK.order(BSK.Splines.basis(S)) - 1   # degree

    return ntuple(p + 1) do k
        k == 1 ? S(x_c) : (BSK.Splines.Derivative(k - 1) * S)(x_c) / T(factorial(k - 1))
    end
end


