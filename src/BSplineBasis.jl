"""
    SingleBSpline{T,N,...}

Wraps a single B-spline basis function from a BSplineKit basis. The struct is
fully parametric in the wrapped BSplineKit object types (basis, basis function,
spline, and its derivative/antiderivative splines) so that all evaluations
dispatch statically; construct via `SingleBSpline(basis, j)` and let the
parameters be inferred.

Fields
- `basis`          : BSpline basis of which the spline is part
- `basis_function` : the b-spline as a `BSplineKit.BSplines.BasisFunction`
- `spline`         : the b-spline as a `BSplineKit.Spline{T}`
- `spline_anti_d`  : antiderivative of the spline
- `spline_d2`      : second derivative of the spline
- `spline_d4`      : fourth derivative of the spline (zero closure for p < 4)
- `j`              : basis index (1..n) in the parent basis
- `p`              : degree; N = p+1 is the number of monomial coeffs per piece
- `knots`          : full knot vector of the parent basis, including endpoint
                     multiplicities and any stacked interior knots
- `pieces`         : per-span polynomial pieces represented on [0,1]
- `support`        : 1 or 2 non-wrapping intervals in [0,1] (2 only if a
                     periodic support wraps around 0/1)
- `mass`           : total integral ∫₀¹ ϕ dx
"""
struct SingleBSpline{T,N,BAS,BF,SP,SPI,SPD2,SPD4}
    basis::BAS
    basis_function::BF 
    spline::SP
    spline_anti_d::SPI
    spline_d2::SPD2
    spline_d4::SPD4
    j::Int
    p::Int
    knots::Vector{T}
    pieces::Vector{PolyPiece{T,N}}
    support::Vector{NTuple{2,T}}
    mass::T
end

"""
Construct a SingleBSpline wrapper for the j-th basis function in `basis`.
"""
function SingleBSpline(basis::BAS, j::Int) where {BAS<:BSK.BSplines.AbstractBSplineBasis}
    T = eltype(BSK.BSplines.knots(basis))
    P = BSK.BSplines.order(basis) - 1   # degree
    N = P + 1                            # number of monomial coefficients

    # One-hot spline
    coeffs = zeros(T, length(basis))
    coeffs[j] = one(T)
    spline = BSK.Splines.Spline(basis, coeffs)
    spline_anti_d = BSK.Splines.integral(spline)
    mass = spline_anti_d(one(T)) - spline_anti_d(zero(T))

    # Derivatives
    D2  = (P ≥ 2) ? (BSK.Splines.Derivative(2) * spline) : x -> zero(T) # Loses spline metadata but we only need correct eval downstream
    D4  = (P ≥ 4) ? (BSK.Splines.Derivative(4) * spline) : x -> zero(T) # Loses spline metadata but we only need correct eval downstream

    # Basis function object
    bf = basis[j]

    # Build pieces (P-parametric) and fill in their centered-monomial coefficients
    pcs = polynomial_pieces(bf, Val(P))
    pcs_filled = PolyPiece{T,N}[with_coeffs(pce, centered_monomial_coeffs(spline, pce.x0))
                                for pce in pcs]

    #support interval(s)
    support = Utils.union_intervals(poly_intervals(bf))

    return SingleBSpline{T,N, typeof(basis), typeof(bf), typeof(spline), typeof(spline_anti_d), typeof(D2), typeof(D4)}(
        basis, bf, spline, spline_anti_d, D2, D4, j, P, collect(T, BSK.BSplines.knots(basis)), pcs_filled, support, mass
    )
end


# evaluation, derivative evaluation
@inline (ϕ::SingleBSpline{T,N,BAS,BF,SP})(x::T) where {T<:AbstractFloat,N,BAS,BF,SP} =
    ϕ.basis_function(x)

    
@inline function evaluate(ϕ::SingleBSpline{T,N,BAS,BF,SP}, x::T) :: T where {T<:AbstractFloat,N,BAS,BF,SP}
    return ϕ(x)
end

@inline function first_derivative(ϕ::SingleBSpline{T,N,BAS,BF,SP}, x::T)::T where {T<:AbstractFloat,N,BAS,BF,SP}
    return (BSK.Splines.Derivative(1) * ϕ.spline)(x)
end

@inline function second_derivative(ϕ::SingleBSpline{T,N,BAS,BF,SP,SPD2}, x::T)::T where {T<:AbstractFloat,N,BAS,BF,SP,SPD2}
    return ϕ.spline_d2(x)
end


"""
build_single_splines(basis::B) where {B<:BSK.BSplines.AbstractBSplineBasis}

Constructs all SingleBSpline objects for the given B-spline basis. Returns a
vector of SingleBSpline{T,N} objects, where T is the floating-point type of the
knots and N = degree+1.
"""
function build_single_splines(basis::B) where  {B<:BSK.BSplines.AbstractBSplineBasis}
    # Comprehension yields a concretely-typed vector (all SingleBSplines from one
    # basis share the same type parameters), avoiding dynamic dispatch downstream.
    return [SingleBSpline(basis, j) for j in 1:length(basis)]
end


"""
    integrate_bspline(ϕ::SingleBSpline{T}, a::T, b::T, nodes, weights) -> T
    integrate_bspline(ϕ::SingleBSpline{T}, intervals, nodes, weights)  -> T
    integrate_bspline(ϕ, a, b)          -> T   # convenience, computes the GL rule internally
    integrate_bspline(ϕ, intervals)     -> T   # convenience

Compute ∫ₐᵇ ϕ(x) dx exactly by splitting [a, b] at the knots of ϕ and applying
Gauss-Legendre quadrature on each knot-free piece, where ϕ is a single
polynomial of degree `ϕ.p`.

The `intervals` form accepts a `Tuple` of `(a, b)` pairs or an `AbstractVector` of pairs, and
returns the sum of the single-interval integrals.

Arguments
---------
- `ϕ`               : the B-spline wrapper (knots sorted, values in [0,1])
- `a`, `b`          : integration limits with 0 ≤ a ≤ b ≤ 1 (non-wrapping)
- `nodes`, `weights`: Gauss-Legendre rule on [-1,1] in type `T` with
                      `length(nodes) ≥ cld(ϕ.p + 1, 2)` for exactness
                      (generate once via `legendre(BigFloat, n)` and cast to `T`,
                      as elsewhere in the package). The convenience methods
                      without `nodes`/`weights` compute this rule per call —
                      fine for tests/scripts, avoid in hot loops.
"""
function integrate_bspline(
    ϕ       :: SingleBSpline{T},
    a       :: T,
    b       :: T,
    nodes   :: Vector{T},
    weights :: Vector{T},
) ::T where {T<:AbstractFloat}

    (zero(T) <= a <= b <= one(T)) ||
        throw(ArgumentError("Require 0 ≤ a ≤ b ≤ 1, got a=$a, b=$b"))
    length(nodes) >= cld(ϕ.p + 1, 2) ||
        throw(ArgumentError("Insufficient Gauss-Legendre nodes for exactness: " *
                            "need ≥ $(cld(ϕ.p + 1, 2)) for degree p=$(ϕ.p), got $(length(nodes))."))
    a == b && return zero(T)

    knots = ϕ.knots
    total = zero(T)

    for (sa, sb) in ϕ.support
        lo = max(a, sa)
        hi = min(b, sb)
        hi <= lo && continue

        # Knots strictly inside (lo, hi); duplicates from stacked multiplicities
        # produce zero-width pieces, which the `k > left` guard skips.
        i1 = searchsortedlast(knots, lo) + 1     # first knot > lo
        i2 = searchsortedfirst(knots, hi) - 1    # last knot < hi

        left = lo
        @inbounds for idx in i1:i2
            k = knots[idx]
            if k > left
                total += Utils._gl_integrate(ϕ, left, k, nodes, weights)
                left = k
            end
        end
        if hi > left
            total += Utils._gl_integrate(ϕ, left, hi, nodes, weights)
        end
    end

    return total
end

function integrate_bspline(
    ϕ         :: SingleBSpline{T},
    intervals :: Union{Tuple{Vararg{NTuple{2,T}}}, AbstractVector{NTuple{2,T}}},
    nodes     :: Vector{T},
    weights   :: Vector{T},
) ::T where {T<:AbstractFloat}
    total = zero(T)
    for (a, b) in intervals
        total += integrate_bspline(ϕ, a, b, nodes, weights)
    end
    return total
end

# Convenience methods: compute the minimal exact GL rule per call.
function integrate_bspline(ϕ::SingleBSpline{T}, a::T, b::T) ::T where {T<:AbstractFloat}
    ξ, ω = legendre(BigFloat, cld(ϕ.p + 1, 2))
    return integrate_bspline(ϕ, a, b, T.(ξ), T.(ω))
end

function integrate_bspline(
    ϕ         :: SingleBSpline{T},
    intervals :: Union{Tuple{Vararg{NTuple{2,T}}}, AbstractVector{NTuple{2,T}}},
) ::T where {T<:AbstractFloat}
    ξ, ω = legendre(BigFloat, cld(ϕ.p + 1, 2))
    return integrate_bspline(ϕ, intervals, T.(ξ), T.(ω))
end


"""
    merge_breakpoints(pts1, pts2; atol=eps(T)) -> Vector{T}

Merge two sorted `AbstractVector`s of breakpoints into one sorted, deduplicated
`Vector{T}`. Points within `atol` of each other are collapsed to the first occurrence.

Used wherever a union mesh of two knot vectors is needed, e.g. for integrating a
product of two piecewise-polynomial functions on different knot grids.
"""
function merge_breakpoints(
    pts1::AbstractVector{T},
    pts2::AbstractVector{T};
    atol::T = eps(T),
) ::Vector{T} where {T<:AbstractFloat}
    out = T[]
    sizehint!(out, length(pts1) + length(pts2))
    i = j = 1
    prev = typemin(T)
    while i ≤ length(pts1) || j ≤ length(pts2)
        val = if j > length(pts2) || (i ≤ length(pts1) && pts1[i] ≤ pts2[j])
            v = pts1[i]; i += 1; v
        else
            v = pts2[j]; j += 1; v
        end
        if val - prev > atol
            push!(out, val)
            prev = val
        end
    end
    return out
end


"""
    convert_precision(ϕ::SingleBSpline{T}, ::Type{S}) -> SingleBSpline{S}
    convert_precision(splines::Vector{<:SingleBSpline{T}}, ::Type{S}) -> Vector{SingleBSpline{S}}

Reconstruct a `SingleBSpline` (or a vector of SingleBSplines) in floating-point
type `S`. The full knot vector (including endpoint multiplicities and any stacked
interior knots) is stored in `ϕ.knots`; passing it with `augment=Val(false)` to
`BSplineBasis` reproduces the identical multiplicity structure in type `S`.

All polynomial coefficients, the antiderivative, and derivative splines are
recomputed entirely in `S` — no rounding is inherited from `T`.

If `T === S` the input is returned unchanged (no copy).
"""
function convert_precision(ϕ::SingleBSpline{T}, ::Type{S}) where {T, S<:AbstractFloat}
    T === S && return ϕ
    new_knots = S.(ϕ.knots)
    new_basis = BSK.BSplineBasis(BSK.BSplineOrder(ϕ.p + 1), new_knots; augment=Val(false))
    return SingleBSpline(new_basis, ϕ.j)
end

function convert_precision(splines::Vector{<:SingleBSpline{T}}, ::Type{S}) where {T, S<:AbstractFloat}
    T === S && return splines
    ϕ1        = splines[1]
    new_knots = S.(ϕ1.knots)
    new_basis = BSK.BSplineBasis(BSK.BSplineOrder(ϕ1.p + 1), new_knots; augment=Val(false))
    return [SingleBSpline(new_basis, j) for j in 1:length(splines)]
end


"""
    build_pm_basis(α::Real, ε::Real, n_outer::Integer, ::Type{T}=Float64;
                   p::Int=3, decouple::Bool=false)

Constructs the B-spline basis for the noisy Pomeau-Manneville map.

If `decouple == false`, returns a standard a spline basis with splines whose supports may straddle
    the boundary layer cutoffs L_ε and 1-L_ε.
If `decouple == true`, returns a basis of splines whose supports are strictly contained in either
    [0,L_ε], [L_ε,1-L_ε], or [1-L_ε,1].

Returns:
- `basis` : The `BSplineBasis` object.
- `L_ε`     : The exact boundary layer scale computed for these parameters.
"""
function build_pm_basis(
    α::Real,
    ε::Real,
    n_outer::Integer,
    ::Type{T}=Float64;
    p::Int=3,
    decouple::Bool=false,
    bdry_layer_constant::T=one(T)
) where {T<:AbstractFloat}

    breaks = hybrid_equidistribution_breakpoints(α, ε, n_outer, T)

    α_T = T(α)
    L_ε   = Utils.boundary_layer_scale(α_T, T(ε))

    if !decouple
        basis = BSK.BSplineBasis(BSplineOrder(p + 1), copy(breaks))
    else
        stack_targets = T[L_ε, one(T) - L_ε]
        knots = build_stacked_knot_vector(breaks, stack_targets; p=p)
        basis = BSK.BSplineBasis(BSplineOrder(p + 1), knots; augment=Val(false))
    end

    return basis, L_ε
end

# -------------------------------------------------
# --- L1 Norm of Difference Between Two Splines ---
# -------------------------------------------------


"""
    l1_norm_difference(splines, c1, c2; atol) -> T
    l1_norm_difference(basis, c1, c2; atol) -> T
    l1_norm_difference(splines1, c1, splines2, c2; atol) -> T
    l1_norm_difference(basis1, c1, basis2, c2; atol) -> T

Compute

    ∫₀¹ |f(x) - g(x)| dx,

where `f` and `g` are linear combinations of B-splines of the same degree.

The calculation uses the piecewise-polynomial structure directly. The two
splines are partitioned into common polynomial spans, their difference is
formed exactly on each span, and the absolute value is integrated by splitting
at its roots.

## Arguments

- `basis` / `splines` :
    Shared B-spline basis or prebuilt `SingleBSpline` objects.

- `basis1`, `basis2` :
    Two B-spline bases of the same order.

- `c1`, `c2` :
    Coefficient vectors defining the two splines.

- `atol` :
    Tolerance used when merging nearby breakpoints, stripping negligible
    leading polynomial coefficients, and skipping degenerate intervals.

# Extended help
## Algorithm

1. Construct the two spline functions `f` and `g`.

2. Merge the distinct knot locations of the two bases to form a common
   partition

       0 = x₀ < x₁ < ... < xₙ = 1.

   The merged knots are used only to determine polynomial spans. The original
   B-spline bases are not modified.

3. On each common span `[a,b]`, neither spline has an interior knot, so both
   `f` and `g` are single degree-`P` polynomials. At the midpoint

       x_c = (a + b) / 2,

   `centered_monomial_coeffs` gives the exact local representations

       f(x) = Σₖ fₖ (x - x_c)^k,
       g(x) = Σₖ gₖ (x - x_c)^k.

   Because both expansions use the same center, subtracting their coefficient
   vectors gives the exact polynomial representation of `f - g` on `[a,b]`.

4. Find the interior roots of `f - g` using `_centpoly_roots_in`. These roots
   divide `[a,b]` into subintervals on which `f - g` has constant sign.

5. On each root-free subinterval,

       ∫ |f - g| = |∫ (f - g)|.

   Since `f - g` is a degree-`P` polynomial there, Gauss-Legendre quadrature
   with `ceil((P+1)/2)` nodes evaluates the integral exactly.

The same algorithm is used whether the two splines share a basis or come from
different bases. The current root solver supports polynomial degree at most
three.
"""
function l1_norm_difference end


# Core implementation: two possibly different B-spline bases.
function l1_norm_difference(
    basis1 :: BSK.BSplines.AbstractBSplineBasis,
    c1     :: AbstractVector{T},
    basis2 :: BSK.BSplines.AbstractBSplineBasis,
    c2     :: AbstractVector{T};
    atol   :: T = eps(T),
) ::T where {T<:AbstractFloat}

    length(c1) == length(basis1) ||
        throw(ArgumentError(
            "c1 must have length $(length(basis1)); got $(length(c1))"
        ))

    length(c2) == length(basis2) ||
        throw(ArgumentError(
            "c2 must have length $(length(basis2)); got $(length(c2))"
        ))

    order = BSK.BSplines.order(basis1)
    BSK.BSplines.order(basis2) == order ||
        throw(ArgumentError(
            "bases must have the same B-spline order; got " *
            "$order and $(BSK.BSplines.order(basis2))"
        ))

    P = order - 1
    P ≤ 3 ||
        throw(ArgumentError(
            "l1_norm_difference currently supports degree ≤ 3; got degree $P"
        ))

    # Construct the original splines. They remain in their own bases throughout
    # the calculation; no interpolation onto a common basis is performed.
    S1 = BSK.Splines.Spline(basis1, c1)
    S2 = BSK.Splines.Spline(basis2, c2)

    # Merge knot locations only to determine intervals on which both splines
    # are single polynomials. Repeated/stacked knots remain part of the original
    # bases; their multiplicities are not altered.
    knots1 = T[
        x for x in BSK.knots(basis1)
        if zero(T) <= x <= one(T)
    ]
    knots2 = T[
        x for x in BSK.knots(basis2)
        if zero(T) <= x <= one(T)
    ]

    breaks = merge_breakpoints(knots1, knots2; atol=atol)

    length(breaks) ≥ 2 ||
        throw(ArgumentError("bases must contain knots spanning [0,1]"))

    abs(breaks[1]) ≤ atol ||
        throw(ArgumentError("bases must contain the left endpoint 0"))

    abs(breaks[end] - one(T)) ≤ atol ||
        throw(ArgumentError("bases must contain the right endpoint 1"))

    # Make the integration endpoints exact after the tolerance checks above.
    breaks[1]   = zero(T)
    breaks[end] = one(T)

    # A degree-P polynomial is integrated exactly by n-point Gauss-Legendre
    # quadrature whenever 2n - 1 ≥ P.
    n_gl = (P + 2) ÷ 2
    ξB, ωB = legendre(BigFloat, n_gl)
    nodes   = T.(ξB)
    weights = T.(ωB)

    total = zero(T)

    for k in 1:length(breaks)-1
        a = breaks[k]
        b = breaks[k+1]

        b - a ≤ atol && continue

        # Since [a,b] contains no interior knot from either basis, S1 and S2
        # are each a single polynomial on this entire span. Expanding both
        # about the same midpoint lets us subtract their coefficients directly.
        x0 = (a + b) / T(2)

        coeffs1 = centered_monomial_coeffs(S1, x0)
        coeffs2 = centered_monomial_coeffs(S2, x0)

        c_span = T[
            coeffs1[m] - coeffs2[m]
            for m in 1:P+1
        ]

        # Work in the shifted coordinate t = x - x0.
        da = a - x0
        db = b - x0

        roots = _centpoly_roots_in(c_span, da, db, atol)
        pts   = vcat(da, roots, db)

        # Between consecutive roots the polynomial has constant sign, so
        # ∫|p| = |∫p| and the Gauss-Legendre rule is exact.
        @inbounds for m in 1:length(pts)-1
            u = pts[m]
            v = pts[m+1]

            v - u ≤ atol && continue

            total += abs(
                Utils._gl_integrate(
                    t -> evalpoly(t, c_span),
                    u,
                    v,
                    nodes,
                    weights,
                )
            )
        end
    end

    return total
end


# Shared-basis form: use the same general algorithm with basis1 === basis2.
function l1_norm_difference(
    basis :: BSK.BSplines.AbstractBSplineBasis,
    c1    :: AbstractVector{T},
    c2    :: AbstractVector{T};
    kwargs...
) where {T<:AbstractFloat}

    return l1_norm_difference(basis, c1, basis, c2; kwargs...)
end


