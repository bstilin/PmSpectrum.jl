"""
symmetric_rice_breakpoints(degree::Integer, α::Real, N::Integer) -> Vector{T}

Rice power partition on [0,1], symmetric about 1/2, for endpoint
singularities ~ x^(-α) at x=0 and (1-x)^(-α) at x=1.

Uses q = (2(degree+1) + 1) / (2α + 1) and maps u=i/N by
  x(u) = 0.5*( (u/0.5)^q )          for u ≤ 0.5
         1 - 0.5*( ((1-u)/0.5)^q )  for u >  0.5

- degree : B-spline degree (cubics are degree=3)
- α : exponent (> -1/2 so 2α+1 > 0)
- N : number of elements (returns N+1 breakpoints)
"""
function symmetric_rice_breakpoints(degree::Integer, α::Real, N::Integer)

    k = degree + 1
    k ≥ 1     || throw(ArgumentError("Require degree ≥ 0, got $degree"))
    N ≥ 2     || throw(ArgumentError("Require N ≥ 2, got $N"))
    α > -0.5  || throw(ArgumentError("Require 2α+1 > 0 for a valid q, got α=$α"))

    T = float(typeof(α))
    q = (T(2k) + one(T)) / (T(2)*T(α) + one(T))

    u    = collect(range(zero(T), one(T); length=N+1))
    x    = similar(u)
    half = T(0.5)

    @inbounds for i in eachindex(u)
        ui = u[i]
        if ui ≤ half
            x[i] = half * ((ui/half)^q)
        else
            x[i] = one(T) - half * (((one(T)-ui)/half)^q)
        end
    end

    x[1] = zero(T); x[end] = one(T)   # exact endpoints
    return x
end



"""
    hybrid_equidistribution_breakpoints(α, ε, n_outer, ::Type{T}=Float64) -> Vector{T}

Hybrid breakpoint sequence for a cubic B-spline L² approximation of the noisy symmetric
Pomeau--Manneville invariant density. The breakpoints in `[0, 1/2]` are constructed from
two pieces and then reflected over `x = 1/2`.

- **Inner region** `[0, L_ε]`: breakpoints are geometrically graded. The mesh ratio
  `r ∈ [1, 2]` is chosen so that the geometric series exactly covers `L_ε`, while the
  spacing at the matching point `L_ε` agrees with the first outer interval.

- **Outer region** `[L_ε, 1/2]`: breakpoints are generated by the de Boor L² power
  partition, equidistributed with respect to the monitor function
  `x^((1 - 2α)/9 - 1)`. Equivalently, the outer breakpoints are

      x_i = (L_ε^γ + (i/n_outer) * ((1/2)^γ - L_ε^γ))^(1/γ),
      γ = (1 - 2α)/9.

  When `γ = 0`, corresponding to `α = 1/2`, this is replaced by the limiting
  log-linear spacing

      x_i = exp(log(L_ε) + (i/n_outer) * (log(1/2) - log(L_ε))).

The matching point `L_ε` is the boundary-layer scale. It separates the inner plateau
region from the outer power-law region.

Arguments:
- `α`       : PM exponent, with `0 < α < 1`
- `ε`       : noise parameter
- `n_outer` : number of equal-mass intervals in `[L_ε, 1/2]`; contributes
              `n_outer - 1` interior outer breakpoints
- `T`       : floating-point precision, e.g. `Float64`, `Double64`, `BigFloat`
"""
function hybrid_equidistribution_breakpoints(
    α::Real, ε::Real, n_outer::Integer, ::Type{T}=Float64
) where {T<:AbstractFloat}

    0 < α < 1     || throw(ArgumentError("Require 0 < α < 1, got α=$α"))
    ε > 0         || throw(ArgumentError("Require ε > 0, got ε=$ε"))
    n_outer ≥ 2   || throw(ArgumentError("Require n_outer ≥ 2, got n_outer=$n_outer"))

    α_T  = T(α)
    half = one(T) / T(2)

    L_ε = Utils.boundary_layer_scale(α_T, T(ε))
    γ   = (one(T) - T(2) * α_T) / T(9)

    # Outer region: de Boor L² power partition on [L_ε, 1/2].
    outer_breakpoints = if iszero(γ) || abs(γ) ≤ sqrt(eps(T)) || !isfinite(one(T) / γ)
        log_L = log(L_ε)
        log_h = log(half)

        T[
            exp(log_L + T(i) / T(n_outer) * (log_h - log_L))
            for i in 1:n_outer-1
        ]
    else
        L_ε_γ = L_ε^γ
        Δ_γ   = half^γ - L_ε_γ

        T[
            (L_ε_γ + T(i) / T(n_outer) * Δ_γ)^(one(T) / γ)
            for i in 1:n_outer-1
        ]
    end

    h_outer0 = outer_breakpoints[1] - L_ε

    # Inner region: geometric grading on [0, L_ε], matched to the first outer spacing.
    inner_breakpoints = if L_ε ≤ eps(T) * half
        T[]   # Degenerate inner region: L_ε is numerically indistinguishable from zero.
    elseif h_outer0 ≥ L_ε
        T[]   # A single interval [0, L_ε] is already no larger than the first outer interval.
    else
        n_inner_intervals = ceil(Int, log2(one(T) + L_ε / h_outer0))

        ratio = L_ε / h_outer0

        # Below this |r - 1|, the geometric sum (r^n - 1)/(r - 1) is evaluated by
        # its r → 1 limit to avoid 0/0. Value chosen (not derived); kept fixed for
        # reproducibility of previously generated meshes.
        r_unit_tol = T(1e-10)

        r = if n_inner_intervals == 1 || ratio ≤ T(n_inner_intervals)
            # Uniform spacing already keeps each inner step no larger than h_outer0.
            one(T)
        else
            geo(r) = abs(r - one(T)) < r_unit_tol ?
                T(n_inner_intervals) :
                (r^n_inner_intervals - one(T)) / (r - one(T))

            find_zero(r -> geo(r) - ratio, (one(T), T(2)), Bisection())
        end

        pts = T[]

        for k in 1:n_inner_intervals-1
            S_k = abs(r - one(T)) < r_unit_tol ?
                T(k) * h_outer0 :
                h_outer0 * (r^k - one(T)) / (r - one(T))

            push!(pts, L_ε - S_k)
        end

        sort!(pts)
    end

    # Assemble the left half and reflect symmetrically over x = 1/2.
    left_half = vcat(
        zero(T),
        inner_breakpoints,
        L_ε,
        outer_breakpoints,
        half,
    )

    right_half = one(T) .- reverse(left_half)

    breakpoints      = vcat(left_half, right_half[2:end])
    breakpoints[1]   = zero(T)
    breakpoints[end] = one(T)

    return breakpoints
end


"""
    build_stacked_knot_vector(breaks, stack_points; p=3, atol)

Expands a strictly increasing vector of breakpoints into a valid knot vector,
stacking knots to multiplicity p+1 at the endpoints and at any specified `stack_points`.
If 'x' is a stack point then no b-spline will have support that straddles 'x'.

Arguments:
- `breaks` : strictly increasing vector of breakpoints (e.g., from `hybrid_equidistribution_breakpoints`)
- `stack_points` : vector of points at which to stack knots
- `p` : spline degree
- `atol` : absolute tolerance for determining if a breakpoint matches a stack point
"""
function build_stacked_knot_vector(
    breaks::Vector{T}, 
    stack_points::Vector{T}; 
    p::Int=3, 
    atol::T=eps(T)
) where {T<:AbstractFloat}

    knots = T[]
    mult  = p + 1

    # Fully stack left endpoint
    append!(knots, fill(breaks[1], mult))

    # Add interior knots, stacking if they match our target points
    for i in 2:(length(breaks)-1)
        pt = breaks[i]
        
        is_stacked = any(s -> abs(pt - s) <= atol, stack_points)
        if is_stacked
            append!(knots, fill(pt, mult))
        else
            push!(knots, pt)
        end
    end

    # Fully stack right endpoint
    append!(knots, fill(breaks[end], mult))

    return knots
end



